#!/usr/bin/env node
// Generate CSS custom properties from the design tokens.
//
//   node tools/tokens.ts             writes viewer/tokens.css
//
// Tokens use the W3C Design Tokens format ($value, $type, {references}).
//   design/tokens/primitives.json   raw palette and font stacks; never emitted
//   design/tokens/foundation.json   grid, space, radius, type, motion
//   design/tokens/components.json   component sizes, read by the layout at runtime
//   design/themes/*.json            colours and shadows, one file per theme
//
// Only semantic and component tokens reach CSS, so components cannot use raw values.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { isMain } from "./is-main.ts";

// A token's value: a string, a number, a list (cubic-bezier) or an object (typography), any of
// which may hold {references} to other tokens.
type Value = string | number | Value[] | { [key: string]: Value };
interface Token { value: Value; type: string | undefined }
type Tokens = Map<string, Token>;
interface Theme { name: string; scheme: "light" | "dark"; system?: boolean; tokens: Tokens }
interface TokenNode { $type?: string; $value?: Value; [key: string]: unknown }

export interface BuiltTokens {
  css: string;
  themes: string[];
  // theme name → token path → resolved colour
  colors: Record<string, Map<string, string>>;
  // Every custom property in :root outside the themes, by name without "--", as the page sees it.
  values: Map<string, string>;
  statuses: string[];
}

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const read = (p: string) => JSON.parse(readFileSync(join(root, p), "utf8"));

export function buildTokens(): BuiltTokens {
  const primitives = flatten(read("design/tokens/primitives.json"));
  const foundation = flatten(read("design/tokens/foundation.json"));
  const components = flatten(read("design/tokens/components.json"));
  const themes: Theme[] = readdirSync(join(root, "design/themes"))
    .filter((f) => f.endsWith(".json"))
    .map((f) => {
      const doc = read(join("design/themes", f));
      return { ...doc.$extensions.openarc, tokens: flatten(doc) };
    });

  // A theme marked "system" is the one the page uses when the reader's setting matches its
  // scheme. The light one is also the fallback in :root.
  const system = (scheme: Theme["scheme"]) => {
    const found = themes.filter((t) => t.system && t.scheme === scheme);
    if (found.length > 1) throw new Error(`more than one ${scheme} theme is marked "system": ${found.map((t) => t.name).join(", ")}`);
    return found[0] as Theme | undefined;
  };
  const fallback = system("light") ?? themes[0];
  const dark = system("dark");
  const expected = [...fallback.tokens.keys()].sort().join();
  for (const t of themes) {
    const keys = [...t.tokens.keys()].sort().join();
    if (keys !== expected) {
      const a = new Set(fallback.tokens.keys()), b = new Set(t.tokens.keys());
      const missing = [...a].filter((k) => !b.has(k)), extra = [...b].filter((k) => !a.has(k));
      throw new Error(`theme "${t.name}" does not match "${fallback.name}"; missing: ${missing.join(", ") || "none"}; extra: ${extra.join(", ") || "none"}`);
    }
  }

  const all: Tokens = new Map([...primitives, ...foundation, ...components, ...fallback.tokens]);
  const decls = (tokens: Iterable<[string, Token]>, scope: Tokens) => [...tokens].flatMap(([path, token]) => toCSS(path, token, resolve(token.value, scope)));

  const base = decls([...foundation, ...components], all);
  const themeBlock = (t: Theme) => {
    const scope = new Map([...all, ...t.tokens]);
    return [...decls(t.tokens, scope), `color-scheme: ${t.scheme};`];
  };
  const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => "  " + l).join("\n")}\n}`;

  const out = [
    "/* Generated by tools/tokens.ts from design/. Do not edit by hand. */",
    block(":root", [...base, ...themeBlock(fallback)]),
    // :root already holds the fallback theme, so data-theme="<fallback>" needs no block.
    ...themes.filter((t) => t !== fallback).map((t) => block(`:root[data-theme="${t.name}"]`, themeBlock(t))),
  ];
  if (dark && dark !== fallback) out.push(`@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', themeBlock(dark)).replace(/^/gm, "  ")}\n}`);

  // One class per text role, so markup applies a role instead of repeating its parts.
  for (const [path, token] of foundation) {
    if (token.type !== "typography") continue;
    const name = path.replace(/\./g, "-");
    out.push(block(`.${name}`, [`font: var(--${name}-font);`, `letter-spacing: var(--${name}-tracking);`, `text-transform: var(--${name}-case);`]));
  }

  // One class per status, setting --st-solid, --st-text and --st-subtle, so a component styles
  // every status with one rule and a new status in the themes needs no new CSS.
  const statuses = [...new Set([...fallback.tokens.keys()].map((p) => p.match(/^color\.status\.([\w-]+)\./)?.[1]).filter((s) => s !== undefined))];
  for (const s of statuses) {
    out.push(block(`.s-${s}`, ["solid", "text", "subtle"].map((v) => `--st-${v}: var(--color-status-${s}-${v});`)));
  }

  // Each theme's colours, fully resolved, for checks such as contrast.
  const colors = Object.fromEntries(themes.map((t) => {
    const scope = new Map([...all, ...t.tokens]);
    return [t.name, new Map([...t.tokens].filter(([, tok]) => tok.type === "color").map(([p, tok]) => [p, String(resolve(tok.value, scope))]))];
  }));

  const values = new Map(base.map((d) => d.match(/^--([\w-]+): (.*);$/)).filter((m) => m !== null).map((m) => [m[1], m[2]]));

  return { css: out.join("\n\n") + "\n", themes: themes.map((t) => t.name), colors, statuses, values };
}

// ---------------------------------------------------------------------------

function flatten(node: TokenNode, path: string[] = [], type?: string, out: Tokens = new Map()): Tokens {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$") || child === null || typeof child !== "object") continue;
    const c = child as TokenNode;
    const t = c.$type ?? type;
    if ("$value" in c) out.set([...path, key].join("."), { value: c.$value!, type: t });
    else flatten(c, [...path, key], t, out);
  }
  return out;
}

function resolve(value: Value, scope: Tokens, seen: string[] = []): Value {
  if (typeof value === "string") {
    const whole = value.match(/^\{([^}]+)\}$/);
    if (whole) return resolve(lookup(whole[1], scope, seen), scope, [...seen, whole[1]]);
    return value.replace(/\{([^}]+)\}/g, (_, ref: string) => String(resolve(lookup(ref, scope, seen), scope, [...seen, ref])));
  }
  if (Array.isArray(value)) return value.map((v) => resolve(v, scope, seen));
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, scope, seen)]));
  return value;
}

function lookup(ref: string, scope: Tokens, seen: string[]): Value {
  if (seen.includes(ref)) throw new Error(`token reference cycle: ${[...seen, ref].join(" -> ")}`);
  const t = scope.get(ref);
  if (!t) throw new Error(`unknown token reference {${ref}}`);
  return t.value;
}

function toCSS(path: string, token: Token, value: Value): string[] {
  const name = "--" + path.replace(/\./g, "-");
  switch (token.type) {
    case "typography": {
      const v = value as Record<string, Value | undefined>;
      return [
        `${name}-font: ${v.fontWeight} ${v.fontSize}/${v.lineHeight} ${v.fontFamily};`,
        `${name}-size: ${v.fontSize};`,
        `${name}-line: ${v.lineHeight};`,
        `${name}-tracking: ${v.letterSpacing ?? "0em"};`,
        `${name}-case: ${v.textTransform ?? "none"};`,
      ];
    }
    case "cubicBezier":
      return [`${name}: cubic-bezier(${(value as Value[]).join(", ")});`];
    default:
      return [`${name}: ${value};`];
  }
}

if (isMain(import.meta.url)) {
  const { css, themes } = buildTokens();
  writeFileSync(join(root, "viewer/tokens.css"), css);
  console.log(`✓ viewer/tokens.css (themes: ${themes.join(", ")})`);
}
